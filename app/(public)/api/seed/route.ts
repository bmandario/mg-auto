export async function GET() {
  try {
    // Clear existing cars first
    const existing = await getDocs(collection(db, "cars"));
    const deletePromises = existing.docs.map((d) => deleteDoc(doc(db, "cars", d.id)));
    await Promise.all(deletePromises);

    // Insert dummy cars
    const insertPromises = DUMMY_CARS.map((car) => addDoc(collection(db, "cars"), car));
    const results = await Promise.all(insertPromises);

    return NextResponse.json({
      success: true,
      message: `Seeded ${results.length} cars successfully.`,
      cars: DUMMY_CARS.map((c, i) => ({ id: results[i].id, name: `${c.year} ${c.brand} ${c.model}`, status: c.status })),
    });
  } catch (error: unknown) {
    const message = error instanceof Error ? error.message : "Unknown error";
    return NextResponse.json({ success: false, error: message }, { status: 500 });
  }
}
